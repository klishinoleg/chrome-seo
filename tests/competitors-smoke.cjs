/* Batch SERP collection and durable CSV reports through actual Chrome extension flows. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
let browser, checks = 0;
const check = (condition, label) => { assert.ok(condition, label); checks++; console.log(`PASS ${label}`); };
const escape = value => String(value).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
(async () => {
  const root = path.resolve(__dirname, '..');
  const installed = 'C:/Program Files/Google/Chrome/Application/chrome.exe';
  browser = await chromium.launchPersistentContext('', { executablePath: process.env.CHROME_PATH || (fs.existsSync(installed) ? installed : undefined), headless: true, viewport: { width: 1200, height: 800 }, args: ['--enable-unsafe-extension-debugging'], ignoreDefaultArgs: ['--disable-extensions'] });
  const cdp = await browser.browser().newBrowserCDPSession();
  const { id } = await cdp.send('Extensions.loadUnpacked', { path: root });
  const admin = await browser.newPage();
  await admin.goto(`chrome-extension://${id}/popup.html`);
  await admin.evaluate(() => chrome.storage.local.set({ searchTargetDomain: 'leader.example', searchQuery: '' }));
  const visits = [], scenarios = new Map();
  const urlFor = (engine, query, page = 1) => engine === 'google' ? `https://www.google.com/search?q=${encodeURIComponent(query)}&start=${(page - 1) * 10}` : `https://yandex.ru/search/?text=${encodeURIComponent(query)}&p=${page - 1}`;
  for (const host of ['www.google.com', 'yandex.ru']) await browser.route(`https://${host}/**`, async route => {
    const url = new URL(route.request().url()), engine = host.includes('google') ? 'google' : 'yandex';
    const query = url.searchParams.get(engine === 'google' ? 'q' : 'text') || '';
    const page = engine === 'google' ? Math.floor(Number(url.searchParams.get('start') || 0) / 10) + 1 : Number(url.searchParams.get('p') || 0) + 1;
    if (route.request().isNavigationRequest() && url.pathname.startsWith('/search')) visits.push({ engine, query, page });
    const scenario = scenarios.get(query) || {};
    const cards = Array.from({ length: 10 }, (_, index) => {
      const n = index + 1;
      const shared = query.startsWith('=') ? 5 : 2;
      const hostname = n === 1 ? 'leader.example' : n === shared ? (query.startsWith('=') ? 'shared.example' : 'www.shared.example') : `site-${query.startsWith('=') ? 'b' : 'a'}-${page}-${n}.example`;
      const href = `https://${hostname}/page-${page}-${n}`;
      return engine === 'google' ? `<div class="MjjYud"><div class="g"><a href="${href}"><h3>Result ${page}-${n}</h3></a><a href="${href}">Sitelink</a></div></div>` : `<li class="serp-item"><div class="Organic"><h2><a class="OrganicTitle-Link" href="${href}">Result ${page}-${n}</a></h2></div></li>`;
    }).join('');
    const next = scenario.end === page ? '' : `<a ${engine === 'google' ? 'id="pnnext"' : 'class="Pager-Item_type_next"'} href="${escape(urlFor(engine, query, page + 1))}">Next</a>`;
    await route.fulfill({ contentType: 'text/html; charset=utf-8', body: `<!doctype html><html lang="ru"><head><title>Batch fixture</title></head><body style="font:16px Arial;margin:40px 300px"><h1>${escape(query)}</h1>${engine === 'google' ? `<div id="rso">${cards}</div>` : `<ul class="serp-list">${cards}</ul>`}${next}</body></html>` });
  });
  const page = await browser.newPage(), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const state = async () => {
    const response = await admin.evaluate(() => chrome.runtime.sendMessage({ type: 'seoRankRun', action: 'getStatus' }));
    assert.ok(response.ok, response.error); return response.state;
  };
  const waitState = async (predicate, timeout = 70000) => {
    const end = Date.now() + timeout;
    while (Date.now() < end) {
      const current = await state(); if (predicate(current)) return current;
      await new Promise(resolve => setTimeout(resolve, 150));
    }
    throw new Error(`Batch timeout: ${JSON.stringify(await state())}`);
  };
  const reportCall = async (action, values = {}) => {
    const response = await admin.evaluate(message => chrome.runtime.sendMessage(message), { type: 'seoCompetitors', action, ...values });
    assert.ok(response?.ok, response?.error); return response.result;
  };
  const expand = async () => {
    await page.locator('#rank-toggle').waitFor();
    if (await page.locator('#rank-toggle').getAttribute('aria-expanded') === 'false') await page.locator('#rank-toggle').click();
  };
  const begin = async (engine, queries, limit) => {
    const previousRunId = (await state())?.id;
    await page.goto(urlFor(engine, 'batch warmup'));
    await expand();
    await page.locator('#rank-mode').selectOption('collect');
    await page.locator('#rank-queries').fill(queries.join('\n'));
    await page.locator('#rank-limit').selectOption(String(limit));
    await page.locator('#rank-engine').selectOption(engine);
    await page.locator('#rank-start').click();
    await waitState(current => current?.id && current.id !== previousRunId);
  };
  await page.goto(urlFor('google', 'batch warmup'));
  await page.locator('#rank-toggle').waitFor();
  check(await page.locator('#rank-toggle').getAttribute('aria-expanded') === 'false' && !(await page.locator('#rank-query').isVisible()), 'search badge starts collapsed without bulky query form');
  await expand();
  check(await page.locator('#rank-query').isVisible(), 'toggle reveals search controls');
  await page.locator('#rank-toggle').click();
  await page.reload();
  await page.locator('#rank-toggle').waitFor();
  check(await page.locator('#rank-toggle').getAttribute('aria-expanded') === 'false', 'collapsed preference survives navigation');
  check((await state()) === null, 'collapse expand and navigation never start collection');
  await begin('google', ['обычный запрос', 'обычный запрос', '=SUM(1,2)'], 30);
  let current = await waitState(state => state?.status === 'completed');
  await page.waitForURL(`chrome-extension://${id}/competitors.html?report=*`);
  let report = (await reportCall('get', { reportId: current.reportId })).report;
  check(report.queries.length === 2 && report.rows.length === 60 && report.limit === 30, 'TOP30 deduplicates queries and collects30 cards for each query');
  check(report.queries.every(query => report.rows.filter(row => row.query === query).at(-1).position === 30), 'positions reset independently for each query');
  check(visits.filter(visit => report.queries.includes(visit.query)).length === 6, 'two TOP30 queries request exactly six result pages');
  check(report.rows.some(row => row.hostname === 'leader.example') && report.rows.length === 60, 'competitor mode collects all results without stopping at saved target domain');
  check(page.url().includes(current.reportId), 'completed batch automatically redirects to its own results page');
  await page.locator('#competitors-summary').waitFor();
  const shared = page.locator('#competitors-summary tr').filter({ hasText: 'shared.example' });
  await shared.waitFor();
  const sharedText = await shared.textContent();
  check(await shared.count() === 1 && /3[.,]5/.test(sharedText), 'www hosts merge and average uses best position per query');
  check((await shared.locator('td').allTextContents()).some(text => text.trim() === '2' || text.trim() === '2 / 2'), 'domain frequency counts two distinct queries rather than six URL occurrences');
  await page.locator('#domain-filter').fill('shared.example');
  check(!(await page.locator('#competitors-summary').textContent()).includes('leader.example'), 'domain filter narrows competitor summary');
  await page.locator('#domain-filter').fill('');
  await page.locator('#query-filter').selectOption(report.queries[0]);
  check(!(await page.locator('#competitors-detail').textContent()).includes('=SUM(1,2)'), 'query filter narrows detailed URL positions');
  await page.locator('#query-filter').selectOption('');
  const detailDownload = page.waitForEvent('download');
  await page.locator('#export-detail').click();
  const detailedFile = await detailDownload;
  const detailBytes = fs.readFileSync(await detailedFile.path());
  const detailCsv = detailBytes.toString('utf8');
  check(detailBytes.subarray(0, 3).equals(Buffer.from([239, 187, 191])) && detailedFile.suggestedFilename().endsWith('.csv'), 'detailed CSV downloads as UTF8 with Excel BOM');
  check(detailCsv.includes(';') && detailCsv.includes("'=SUM(1,2)"), 'CSV uses semicolon and escapes formula-like search queries');
  const summaryDownload = page.waitForEvent('download');
  await page.locator('#export-summary').click();
  const summaryCsv = fs.readFileSync(await (await summaryDownload).path(), 'utf8');
  check(summaryCsv.includes('shared.example') && summaryCsv.includes('leader.example'), 'separate summary CSV exports domain statistics');
  const workerTarget = (await cdp.send('Target.getTargets')).targetInfos.find(target => target.type === 'service_worker' && target.url === `chrome-extension://${id}/background.js`);
  await cdp.send('Target.closeTarget', { targetId: workerTarget.targetId });
  await page.reload();
  await page.locator('#competitors-summary').waitFor();
  check((await reportCall('get', { reportId: report.id })).report.rows.length === 60, 'private report data survives actual worker restart and page reload');
  await begin('yandex', ['полный топ100'], 100);
  current = await waitState(state => state?.status === 'completed', 80000);
  await page.waitForURL(`chrome-extension://${id}/competitors.html?report=*`);
  report = (await reportCall('get', { reportId: current.reportId })).report;
  if (report.engine !== 'yandex' || report.rows.length !== 100 || report.rows.at(-1)?.position !== 100) console.error('Yandex acceptance diagnostics', JSON.stringify({ state: current, report: { engine: report.engine, rows: report.rows.length, last: report.rows.at(-1), queryResults: report.queryResults }, visits: visits.filter(visit => visit.query === 'полный топ100') }));
  check(report.engine === 'yandex' && report.rows.length === 100 && report.rows.at(-1).position === 100, 'Yandex collection reaches TOP100 without page11');
  check(visits.filter(visit => visit.query === 'полный топ100').length === 10, 'TOP100 collection is bounded to ten pages');
  scenarios.set('короткая выдача', { end: 1 });
  await begin('google', ['короткая выдача', 'следующий запрос'], 30);
  current = await waitState(state => state?.status === 'completed');
  await page.waitForURL(`chrome-extension://${id}/competitors.html?report=*`);
  report = (await reportCall('get', { reportId: current.reportId })).report;
  check(report.rows.length === 40 && report.queryResults.some(item => item.query === 'короткая выдача' && item.status === 'partial' && item.count === 10), 'short recognized SERP is marked partial and batch continues to next query');
  await begin('google', ['остановить сбор'], 100);
  await waitState(state => state?.status === 'waiting');
  await page.locator('#rank-toggle').click();
  check(await page.locator('#rank-stop').isVisible(), 'collapsed running badge retains Stop control');
  await page.locator('#rank-stop').click();
  current = await waitState(state => state?.status === 'stopped');
  report = (await reportCall('get', { reportId: current.reportId })).report;
  check(report.rows.length === 10 && report.status !== 'completed', 'Stop saves partial report without claiming complete TOP100');
  await page.locator('#rank-results').click();
  await page.waitForURL(`chrome-extension://${id}/competitors.html?report=*`);
  check((await reportCall('list')).reports.length >= 4, 'earlier reports remain available after later runs');
  const other = await browser.newPage();
  await other.goto(urlFor('google', 'privacy probe'));
  const denied = await admin.evaluate(async url => {
    const tab = (await chrome.tabs.query({})).find(tab => tab.url === url);
    const result = await chrome.scripting.executeScript({ target: { tabId: tab.id }, func: () => chrome.runtime.sendMessage({ type: 'seoCompetitors', action: 'list' }) });
    return result[0].result;
  }, other.url());
  check(denied?.ok === false, 'search content script cannot read private competitor reports');
  check(errors.length === 0, 'batch controls and report filters/export have no uncaught exceptions');
  const evidence = 'C:/Users/klish/.codex/visualizations/2026/10/22/01a1638b-a337-75d1-b3e3-680cfe652ad8';
  fs.mkdirSync(evidence, { recursive: true });
  await page.screenshot({ path: path.join(evidence, 'chrome-seo-competitors.png') });
  console.log(`PASS ${checks} competitor collection/report integration checks (SERPs mocked)`);
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => { await browser?.close(); });

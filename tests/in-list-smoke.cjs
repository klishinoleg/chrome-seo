/* Domain membership badge with real extension worker/storage and page metadata bridge. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
let browser;
let checks = 0;
const check = (condition, label) => { assert.ok(condition, label); checks++; console.log(`PASS ${label}`); };
(async () => {
  const chromePath = 'C:/Program Files/Google/Chrome/Application/chrome.exe';
  browser = await chromium.launchPersistentContext('', { executablePath: process.env.CHROME_PATH || (fs.existsSync(chromePath) ? chromePath : undefined), headless: true, viewport: { width: 800, height: 660 }, args: ['--enable-unsafe-extension-debugging'], ignoreDefaultArgs: ['--disable-extensions'] });
  const cdp = await browser.browser().newBrowserCDPSession();
  const { id } = await cdp.send('Extensions.loadUnpacked', { path: path.resolve(__dirname, '..') });
  const page = await browser.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  let activeUrl = 'https://realsiteworth.com/?url=voice-school.com&run=lite';
  let delay = 0, fail = false;
  const metadata = url => ({ url, hostname: new URL(url).hostname, title: 'Current page', description: '', canonical: '', robots: '', robotMeta: [], lang: 'ru', openGraph: [], headings: [], images: [], wordCount: 1, links: [{ url: 'https://target.example/', domain: 'target.example', text: 'Target', rel: '', restricted: false }], pageNofollow: false, micro: { jsonLd: [], microdata: [], rdfa: [] } });
  await page.exposeFunction('__tabFixture', () => [{ id: 42, url: activeUrl }]);
  await page.exposeFunction('__analyzeFixture', async () => {
    const data = metadata(activeUrl), capturedFail = fail;
    await new Promise(resolve => setTimeout(resolve, delay));
    return capturedFail ? null : data;
  });
  await page.exposeFunction('__probeFixture', () => ({ url: activeUrl, robots: { status: 'ok', httpStatus: 200, text: 'User-agent: *\nAllow: /' }, page: { status: 'ok', httpStatus: 200, xRobotsTag: '' } }));
  await page.addInitScript(() => {
    chrome.tabs.query = async () => __tabFixture();
    chrome.scripting.executeScript = async options => {
      if (options.files) return [];
      const result = options.args?.[0] === 'analyze' ? await __analyzeFixture() : await __probeFixture();
      if (!result) throw new Error('Page access denied');
      return [{ result }];
    };
  });
  await page.goto(`chrome-extension://${id}/popup.html`);
  const badge = page.locator('#in-list-status');
  const state = () => badge.getAttribute('data-state');
  const waitState = expected => page.waitForFunction(expected => document.querySelector('#in-list-status')?.dataset.state === expected, expected);
  const rpc = async (action, payload = {}) => {
    const result = await page.evaluate(message => chrome.runtime.sendMessage(message), { type: 'seoLists', action, ...payload });
    assert.ok(result.ok, result.error); return result.state;
  };
  const refresh = async url => {
    activeUrl = url;
    await page.locator('#refresh').click();
    await page.waitForFunction(url => document.querySelector('#page').textContent === url, url);
  };
  await page.waitForFunction(() => document.querySelector('#page').textContent.startsWith('https://realsiteworth.com/'));
  await waitState('unknown');
  check(await badge.textContent() === 'IN LIST', 'fixed compact IN LIST label is visible without a selected list');
  check((await badge.getAttribute('title')).length > 0, 'unknown state explains why no membership result is available');
  let data = await rpc('createList', { name: 'Первый список' });
  const listA = data.selectedListId;
  await waitState('absent');
  check(true, 'empty selected list immediately shows absent');
  await rpc('addItem', { listId: listA, url: 'https://voice-school.com/en/' });
  await waitState('absent');
  check(await state() === 'absent', 'domain in query string does not count as current site');
  await rpc('addItem', { listId: listA, url: 'https://realsiteworth.com.evil.example/' });
  check(await state() === 'absent', 'hostname suffix lookalike cannot produce a match');
  data = await rpc('addItem', { listId: listA, url: 'http://WWW.RealSiteWorth.COM.:8080/another-path?q=1' });
  const matchingId = data.data.lists.find(list => list.id === listA).items.at(-1).id;
  await waitState('present');
  check(true, 'hostname match normalizes case www trailing dot and ignores scheme path and port');
  const green = await badge.evaluate(node => getComputedStyle(node).color);
  check((await badge.getAttribute('title')).includes('Первый список') && (await badge.getAttribute('aria-label')).includes('realsiteworth.com'), 'accessible tooltip identifies selected list and current domain');
  await refresh('https://realsiteworth.com.evil.example/page');
  await waitState('present');
  await refresh('https://evil-realsiteworth.com/page');
  await waitState('absent');
  check(true, 'current hostname resembling a saved domain remains absent');
  await refresh('https://realsiteworth.com/');
  await waitState('present');
  data = await rpc('createList', { name: 'Второй список' });
  const listB = data.selectedListId;
  await waitState('absent');
  const red = await badge.evaluate(node => getComputedStyle(node).color);
  check(green !== red, 'present and absent have distinct green and red styles');
  check(true, 'matching URL in another list does not count for selected list');
  await rpc('selectList', { listId: listA });
  await waitState('present');
  check(true, 'selection changed from another extension page updates live without refresh');
  await rpc('removeItem', { listId: listA, itemId: matchingId });
  await waitState('absent');
  check(true, 'removing last matching domain updates live');
  const imported = (await rpc('get')).data;
  const importedList = imported.lists.find(list => list.id === listA);
  const timestamp = new Date().toISOString();
  importedList.items.push({ id: 'imported-membership', url: 'https://realsiteworth.com/imported', title: '', comment: '', tags: [], createdAt: timestamp, updatedAt: timestamp });
  await rpc('importData', { data: imported });
  await waitState('present');
  check(true, 'JSON import into selected list updates membership live');
  await rpc('removeItem', { listId: listA, itemId: 'imported-membership' });
  await waitState('absent');
  await page.locator('[data-tab="links"]').click();
  await page.locator('#save-links-page').click();
  await waitState('present');
  check(true, 'LINKS quick save of source page turns badge green');
  await refresh('https://sub.realsiteworth.com/page');
  await waitState('absent');
  check(true, 'other subdomains remain distinct from saved hostname');
  await refresh('https://realsiteworth.com/new-page');
  await waitState('present');
  check(true, 'refresh follows current page while ignoring URL path');
  delay = 500;
  activeUrl = 'https://new.example/';
  await page.locator('#refresh').click();
  await waitState('unknown');
  await rpc('selectList', { listId: listB });
  check(await state() === 'unknown', 'list changes during pending analysis cannot revive stale membership');
  await page.waitForFunction(url => document.querySelector('#page').textContent === url, activeUrl);
  await waitState('absent');
  delay = 0;
  await rpc('addItem', { listId: listB, url: 'https://new.example/stored' });
  await waitState('present');
  fail = true;
  await page.locator('#refresh').click();
  await page.waitForFunction(() => document.querySelector('#status').textContent.includes('Page access denied'));
  check(await state() === 'unknown', 'failed page analysis cannot leave stale green membership');
  fail = false;
  await refresh('https://new.example/back');
  await waitState('present');
  await page.reload();
  await waitState('present');
  check(true, 'reopening popup restores selected list and membership from real storage');
  await rpc('deleteList', { listId: listB });
  await waitState('absent');
  await rpc('deleteList', { listId: listA });
  await waitState('unknown');
  check(true, 'deleting all lists returns neutral state');
  const boxes = await Promise.all(['#page', '#copy-page-url', '#in-list-status', '#indexability-status'].map(selector => page.locator(selector).boundingBox()));
  check(boxes.every(Boolean) && Math.max(...boxes.map(box => box.y + box.height / 2)) - Math.min(...boxes.map(box => box.y + box.height / 2)) < 6, 'URL copy membership and indexing remain on a compact single row');
  fs.mkdirSync(path.join(__dirname, 'artifacts'), { recursive: true });
  await page.screenshot({ path: path.join(__dirname, 'artifacts', 'in-list.png') });
  check(errors.length === 0, 'membership workflow has no uncaught JavaScript exceptions');
  console.log(`PASS ${checks} domain list membership integration checks`);
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => { await browser?.close(); });

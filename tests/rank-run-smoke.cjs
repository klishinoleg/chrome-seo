/* Real MV3 SERP controls and navigation; search responses are local route fixtures. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
let browser, checks = 0;
const check = (condition, label) => { assert.ok(condition, label); checks++; console.log(`PASS ${label}`); };
const escape = value => String(value).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
(async () => {
  const root = path.resolve(__dirname, '..');
  const evidence = 'C:/Users/klish/.codex/visualizations/2026/10/22/01a1638b-a337-75d1-b3e3-680cfe652ad8';
  fs.mkdirSync(evidence, { recursive: true });
  const chromePath = 'C:/Program Files/Google/Chrome/Application/chrome.exe';
  browser = await chromium.launchPersistentContext('', { executablePath: process.env.CHROME_PATH || (fs.existsSync(chromePath) ? chromePath : undefined), headless: true, viewport: { width: 1100, height: 760 }, args: ['--enable-unsafe-extension-debugging'], ignoreDefaultArgs: ['--disable-extensions'] });
  const cdp = await browser.browser().newBrowserCDPSession();
  const { id } = await cdp.send('Extensions.loadUnpacked', { path: root });
  const admin = await browser.newPage();
  await admin.goto(`chrome-extension://${id}/popup.html`);
  await admin.evaluate(() => chrome.storage.local.set({ searchTargetDomain: 'target.example', searchQuery: '' }));
  const scenarios = new Map();
  const visits = [];
  const errors = [];
  const base = engine => engine === 'google' ? 'https://www.google.com/search' : 'https://yandex.ru/search/';
  const searchUrl = (engine, query, page = 1) => `${base(engine)}?${engine === 'google' ? 'q' : 'text'}=${encodeURIComponent(query)}&${engine === 'google' ? 'start' : 'p'}=${engine === 'google' ? (page - 1) * 10 : page - 1}`;
  const fixture = (engine, query, page, scenario) => {
    if (scenario.captcha === page && !scenario.solved) return '<html><head><title>Подтвердите, что вы не робот</title></head><body><h1>Проверка CAPTCHA</h1><form id="captcha-form"><div class="g-recaptcha"></div><input name="captcha"></form></body></html>';
    if (scenario.unknown === page) return '<html><body><h1>Unsupported changed result layout</h1><a href="https://target.example/">Not an organic result</a></body></html>';
    const count = scenario.size?.[page] ?? 10;
    const cards = [];
    for (let n = 1; n <= count; n++) {
      const found = scenario.foundPage === page && scenario.foundSlot === n;
      const destination = found ? 'https://sub.target.example/article' : scenario.opaque && n === 1 ? 'https://clck.yandex.ru/jsredir?opaque=1' : n === 1 ? 'https://target.example.evil.test/lookalike' : n === 2 ? engine === 'google' ? 'https://developers.google.com/style/examples' : 'https://yandex.ru/support/search/index.html' : `https://site-${page}-${n}.example/article`;
      const anchor = `<a href="${destination}">${engine === 'google' ? `<h3>Organic result ${page}-${n}</h3>` : `Organic result ${page}-${n}`}</a>`;
      const sitelinks = '<a href="https://target.example/sitelink">Extra sitelink without its own result title</a>';
      cards.push(engine === 'google' ? `<div class="MjjYud"><div class="g">${anchor}${sitelinks}</div></div>` : `<li class="serp-item"><div class="Organic"><h2 class="OrganicTitle">${anchor.replace('<a ', '<a class="OrganicTitle-Link" ' )}</h2>${sitelinks}</div></li>`);
    }
    const ad = engine === 'google' ? '<div id="tads"><div data-text-ad><a href="https://target.example/ad"><h3>Sponsored target</h3></a></div></div>' : '<li class="serp-item serp-item_type_ads"><div class="Adv"><h2><a href="https://target.example/ad">Реклама target</a></h2></div></li>';
    const next = scenario.end === page ? '' : `<a ${engine === 'google' ? 'id="pnnext"' : 'class="Pager-Item Pager-Item_type_next"'} href="${escape(scenario.offsite ? 'https://malicious.example/search' : scenario.loop ? searchUrl(engine, query, page) : searchUrl(engine, query, page + 1))}">${engine === 'google' ? 'Next' : 'Дальше'}</a>`;
    return `<!doctype html><html lang="ru"><head><title>Search fixture ${escape(query)}</title><style>body{font:16px Arial;margin:30px 240px 150px}h3,h2{font-size:20px}a{color:#1645ad}.g,.serp-item{margin:20px 0;list-style:none}</style></head><body><form action="${base(engine)}"><input name="${engine === 'google' ? 'q' : 'text'}" value="${escape(query)}"></form><h1>${escape(query)}</h1>${engine === 'google' ? `${ad}<div id="search"><div id="rso">${cards.join('')}</div></div>` : `<main><ul class="serp-list">${ad}${cards.join('')}</ul></main>`}${next}</body></html>`;
  };
  for (const host of ['www.google.com', 'www.google.ru', 'google.com', 'yandex.ru', 'yandex.com']) await browser.route(`https://${host}/**`, async route => {
    const url = new URL(route.request().url());
    const engine = host.includes('google') ? 'google' : 'yandex';
    const query = url.searchParams.get(engine === 'google' ? 'q' : 'text') || '';
    const page = engine === 'google' ? Math.floor(Number(url.searchParams.get('start') || 0) / 10) + 1 : Number(url.searchParams.get('p') || 0) + 1;
    if (url.pathname.startsWith('/search') && route.request().isNavigationRequest()) visits.push({ engine, query, page });
    const scenario = scenarios.get(query) || { end: 1 };
    await route.fulfill({ contentType: 'text/html; charset=utf-8', body: fixture(engine, query, page, scenario) });
  });
  const page = await browser.newPage();
  page.on('pageerror', error => errors.push(error.message));
  const state = async () => {
    const response = await admin.evaluate(() => chrome.runtime.sendMessage({ type: 'seoRankRun', action: 'getStatus' }));
    assert.ok(response?.ok, response?.error); return response.state;
  };
  const waitState = async (predicate, timeout = 45000) => {
    const end = Date.now() + timeout;
    while (Date.now() < end) {
      const current = await state();
      if (predicate(current)) return current;
      await new Promise(resolve => setTimeout(resolve, 150));
    }
    throw new Error(`Rank state timeout: ${JSON.stringify(await state())}`);
  };
  const begin = async (engine, query, scenario, warmupPage = 1) => {
    scenarios.set(query, scenario);
    const previous = await state();
    if (previous && ['running', 'waiting', 'paused'].includes(previous.status)) {
      const stopped = await admin.evaluate(runId => chrome.runtime.sendMessage({ type: 'seoRankRun', action: 'stop', runId }), previous.id);
      assert.ok(stopped.ok, stopped.error);
    }
    await page.goto(searchUrl(engine, 'warmup', warmupPage));
    await page.locator('#rank-start').waitFor();
    await page.locator('#rank-domain').fill('target.example');
    await page.locator('#rank-query').fill(query);
    const before = visits.filter(visit => visit.query === query).length;
    await page.locator('#rank-start').click();
    return before;
  };
  await page.goto(searchUrl('google', 'warmup'));
  await page.locator('#rank-start').waitFor();
  check((await state()) === null, 'SERP badge does not start a rank run on opening');
  const idleVisits = visits.length;
  await page.locator('#rank-query').fill('typing only');
  check(visits.length === idleVisits, 'typing a query never navigates or starts checking');
  await begin('google', 'google found', { foundPage: 2, foundSlot: 3 }, 5);
  let current = await waitState(state => state?.status === 'found');
  check(current.found.position === 13 && current.found.page === 2 && current.found.positionOnPage === 3, 'Google reports absolute rank13 page2 local3');
  check(current.pagesVisited === 2 && current.resultsSeen >= 13 && current.resultsSeen <= 20, 'ads and sitelinks never count as independent organic results');
  check(JSON.stringify(visits.filter(visit => visit.query === 'google found').map(visit => visit.page)) === '[1,2]', 'Play always starts page1 and stops navigating immediately when found');
  check(current.found.url.startsWith('https://sub.target.example/'), 'matching includes subdomain while excluding deceptive hostname');
  check((await page.locator('#rank-status').textContent()).includes('13'), 'found rank is shown on the SERP badge');
  await page.screenshot({ path: path.join(evidence, 'chrome-seo-rank-found.png') });
  await begin('yandex', 'yandex found', { foundPage: 2, foundSlot: 4 });
  current = await waitState(state => state?.status === 'found');
  check(current.engine === 'yandex' && current.found.position === 14 && current.found.page === 2 && current.found.positionOnPage === 4, 'Yandex reports absolute rank14 page2 local4');
  check(visits.filter(visit => visit.query === 'yandex found').length === 2, 'Yandex traverses only necessary pages');
  await begin('google', 'variable results', { foundPage: 2, foundSlot: 2, size: { 1: 7 } });
  current = await waitState(state => state?.status === 'found');
  check(current.found.position === 9 && current.found.page === 2, 'global position counts observed organic cards instead of assuming ten per page');
  await begin('google', 'worker restart', { foundPage: 2, foundSlot: 2 });
  current = await waitState(state => state?.status === 'waiting');
  const restartId = current.id;
  const forbidden = await admin.evaluate(runId => chrome.runtime.sendMessage({ type: 'seoRankRun', action: 'snapshot', runId, snapshot: { kind: 'results', results: [{ url: 'https://target.example/' }] } }), restartId);
  check(!forbidden.ok && (await state()).resultsSeen === 10, 'extension page cannot forge an organic snapshot for bound search tab');
  const staleStop = await admin.evaluate(() => chrome.runtime.sendMessage({ type: 'seoRankRun', action: 'stop', runId: 'old-run-id' }));
  check(!staleStop.ok && (await state()).status === 'waiting', 'stale control message cannot cancel the current run');
  const workerTarget = (await cdp.send('Target.getTargets')).targetInfos.find(target => target.type === 'service_worker' && target.url === `chrome-extension://${id}/background.js`);
  assert.ok(workerTarget);
  await cdp.send('Target.closeTarget', { targetId: workerTarget.targetId });
  current = await waitState(state => state?.status === 'found');
  check(current.id === restartId && current.found.position === 12 && current.pagesVisited === 2, 'actual service-worker restart preserves progress without duplicate counting');
  await begin('google', 'limit pages', {});
  current = await waitState(state => state?.status === 'not-found', 65000);
  check(current.pagesVisited === 10 && current.resultsSeen === 100 && visits.filter(visit => visit.query === 'limit pages').length === 10, 'run stops at tenth page/hundredth organic result without page11');
  await begin('google', 'hundredth result', { foundPage: 10, foundSlot: 10 });
  current = await waitState(state => state?.status === 'found', 65000);
  check(current.found.position === 100 && current.found.page === 10 && current.found.positionOnPage === 10, 'target at exactly position100 is still reported');
  await begin('yandex', 'stop waiting', {});
  await waitState(state => state?.status === 'waiting');
  await page.locator('#rank-stop').click();
  current = await waitState(state => state?.status === 'stopped');
  await new Promise(resolve => setTimeout(resolve, 2800));
  check(visits.filter(visit => visit.query === 'stop waiting').length === 1, 'Stop cancels pending next-page navigation');
  await begin('google', 'captcha pause', { captcha: 2 });
  current = await waitState(state => state?.status === 'paused');
  check(/captcha|капч|робот/i.test(current.reason) && visits.filter(visit => visit.query === 'captcha pause').length === 2, 'CAPTCHA pauses run without bypass or next-page navigation');
  scenarios.set('captcha pause', { foundPage: 2, foundSlot: 1, captcha: 2, solved: true });
  await page.reload();
  await page.locator('#rank-resume').click();
  current = await waitState(state => state?.status === 'found');
  check(current.found.position === 11, 'explicit resume after manual CAPTCHA clearance continues prior count');
  await begin('google', 'unknown layout', { unknown: 1 });
  current = await waitState(state => state?.status === 'paused');
  check(current.resultsSeen === 0 && visits.filter(visit => visit.query === 'unknown layout').length === 1, 'unrecognized layout pauses instead of reporting false absence');
  await begin('yandex', 'opaque destination', { opaque: true });
  current = await waitState(state => state?.status === 'paused');
  check(current.resultsSeen === 0, 'unresolved organic tracking link pauses before shifting rank arithmetic');
  await begin('google', 'invalid next', { offsite: true });
  current = await waitState(state => state?.status === 'paused');
  check(visits.filter(visit => visit.query === 'invalid next').length === 1 && new URL(page.url()).hostname === 'www.google.com', 'untrusted off-site next link cannot redirect automated run');
  await begin('google', 'manual navigation', {});
  await waitState(state => state?.status === 'waiting');
  await page.goto(searchUrl('google', 'user changed query'));
  current = await waitState(state => state?.status === 'paused' || state?.status === 'stopped');
  check(visits.filter(visit => visit.query === 'manual navigation').length === 1, 'manual query change prevents continued old search');
  await begin('google', 'close badge', {});
  await waitState(state => state?.status === 'waiting');
  await page.locator('#rank-close').click();
  current = await waitState(state => state?.status === 'stopped');
  check(true, 'closing the badge stops active checking');
  check(errors.length === 0, 'rank controls and cross-page progress have no uncaught exceptions');
  await page.goto(searchUrl('google', 'google found', 2));
  await page.screenshot({ path: path.join(evidence, 'chrome-seo-rank-run.png') });
  console.log(`PASS ${checks} SERP rank-run integration checks (search pages mocked)`);
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => { await browser?.close(); });

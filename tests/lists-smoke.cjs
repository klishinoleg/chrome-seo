/* Real extension service-worker, storage, IndexedDB and file API integration. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
let browser;
let checks = 0;
const check = (value, label) => { assert.ok(value, label); checks++; console.log(`PASS ${label}`); };
(async () => {
  const chromePath = 'C:/Program Files/Google/Chrome/Application/chrome.exe';
  const executablePath = process.env.CHROME_PATH || (process.platform === 'win32' && fs.existsSync(chromePath) ? chromePath : undefined);
  browser = await chromium.launchPersistentContext('', { executablePath, headless: true, viewport: { width: 1280, height: 850 }, args: ['--enable-unsafe-extension-debugging'], ignoreDefaultArgs: ['--disable-extensions'] });
  const cdp = await browser.browser().newBrowserCDPSession();
  const { id } = await cdp.send('Extensions.loadUnpacked', { path: path.resolve(__dirname, '..') });
  const page = await browser.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`chrome-extension://${id}/library.html`);
  const raw = (action, payload = {}) => page.evaluate(message => chrome.runtime.sendMessage(message), { type: 'seoLists', action, ...payload });
  const rpc = async (action, payload) => { const response = await raw(action, payload); assert.ok(response?.ok, response?.error || `Failed ${action}`); return response.state; };
  const initial = await rpc('get');
  check(initial.data.version === 1 && initial.data.lists.length === 0, 'empty versioned library through real service worker');
  let state = await rpc('createList', { name: 'SEO сайты' });
  const firstId = state.selectedListId;
  check(Boolean(firstId) && state.data.lists[0].name === 'SEO сайты', 'creating list selects it');
  state = await rpc('addItem', { listId: firstId, url: 'https://example.com/page', title: 'Страница <img src=x onerror=alert(1)>', comment: 'Первый комментарий', tags: [' follow ', 'FOLLOW', 'Проверить'] });
  let item = state.data.lists.find(x => x.id === firstId).items[0];
  const itemId = item.id;
  check(item.tags.length === 2 && new Set(item.tags.map(t => t.toLowerCase())).size === 2, 'free tags trimmed and case-insensitively deduplicated');
  check(state.data.lists[0].tags.length === 2, 'current list keeps reusable tag catalogue');
  state = await rpc('createList', { name: 'Второй список' });
  const secondId = state.selectedListId;
  check(state.data.lists.find(x => x.id === secondId).tags.length === 0, 'tag suggestions isolated by list');
  await rpc('selectList', { listId: firstId });
  await page.reload();
  state = await rpc('get');
  check(state.selectedListId === firstId, 'current list selection survives page reload');
  state = await rpc('updateComment', { listId: firstId, itemId, comment: 'Новый комментарий — <script>bad</script>' });
  check(state.data.lists[0].items[0].comment.includes('Новый комментарий'), 'editing saved URL comment persists');
  state = await rpc('updateTags', { listId: firstId, itemId, tags: ['follow', 'Новый тег'] });
  check(state.data.lists[0].tags.some(t => t === 'Проверить') && state.data.lists[0].items[0].tags.includes('Новый тег'), 'tag catalogue persists unused tags and accepts new tags');
  const rejected = await raw('addItem', { listId: firstId, url: 'javascript:alert(1)', title: '', comment: '', tags: [] });
  check(!rejected.ok, 'unsafe URL schemes rejected');
  const beforeInvalid = JSON.stringify((await rpc('get')).data);
  check(!(await raw('importData', { data: { version: 999, lists: [] } })).ok, 'unknown import schema version rejected');
  check(JSON.stringify((await rpc('get')).data) === beforeInvalid, 'invalid import preserves all local records');
  const exported = (await rpc('get')).data;
  state = await rpc('importData', { data: exported });
  check(state.data.lists.length === 2 && state.data.lists[0].items.length === 1, 'reimport is idempotent for unchanged records');
  const old = JSON.parse(JSON.stringify(exported));
  for (const list of old.lists) { delete list.tags; for (const row of list.items) delete row.tags; }
  check((await raw('importData', { data: old })).ok, 'v1 JSON without tags remains compatible');
  await Promise.all(Array.from({ length: 8 }, (_, n) => rpc('addItem', { listId: secondId, url: `https://concurrent.example/${n}`, title: `Parallel ${n}`, comment: '', tags: ['batch'] })));
  state = await rpc('get');
  check(state.data.lists.find(x => x.id === secondId).items.length === 8, 'concurrent popup mutations do not lose records');
  state = await rpc('renameList', { listId: secondId, name: 'Переименованный' });
  check(state.data.lists.find(x => x.id === secondId).name === 'Переименованный', 'renaming list retains its records');
  const prepareDirectory = (name, content) => page.evaluate(async ({ name, content }) => {
    const directory = await (await navigator.storage.getDirectory()).getDirectoryHandle(name, { create: true });
    if (content !== null) { const file = await directory.getFileHandle('seo-lists.json', { create: true }); const stream = await file.createWritable(); await stream.write(content); await stream.close(); }
    const db = await new Promise((resolve, reject) => { const req = indexedDB.open('seoListsFS', 1); req.onupgradeneeded = () => req.result.createObjectStore('handles'); req.onsuccess = () => resolve(req.result); req.onerror = () => reject(req.error); });
    await new Promise((resolve, reject) => { const tx = db.transaction('handles', 'readwrite'); tx.objectStore('handles').put(directory, 'directory'); tx.oncomplete = resolve; tx.onerror = () => reject(tx.error); });
    db.close();
    return directory.name;
  }, { name, content });
  const readDirectoryFile = name => page.evaluate(async name => {
    const directory = await (await navigator.storage.getDirectory()).getDirectoryHandle(name);
    return (await (await directory.getFileHandle('seo-lists.json')).getFile()).text();
  }, name);
  await prepareDirectory('valid-lists', null);
  state = await rpc('connectDirectory');
  check(state.sync.connected && !state.sync.pending, 'chosen directory handle connects and syncs');
  let disk = JSON.parse(await readDirectoryFile('valid-lists'));
  check(disk.version === 1 && disk.lists.some(x => x.items.some(i => i.tags.includes('follow'))), 'JSON file contains URL comments and tags');
  state = await rpc('addItem', { listId: firstId, url: 'https://example.org/new', title: 'Автосохранение', comment: 'На диск', tags: ['follow'] });
  disk = JSON.parse(await readDirectoryFile('valid-lists'));
  check(disk.lists.find(x => x.id === firstId).items.some(x => x.comment === 'На диск'), 'new URL automatically mirrors to JSON');
  await page.reload();
  state = await rpc('sync');
  check(state.sync.connected && state.sync.directoryName === 'valid-lists', 'directory handle survives page reload through IndexedDB');
  const workerTarget = (await cdp.send('Target.getTargets')).targetInfos.find(target => target.type === 'service_worker' && target.url === `chrome-extension://${id}/background.js`);
  assert.ok(workerTarget, 'extension service worker target exists');
  await cdp.send('Target.closeTarget', { targetId: workerTarget.targetId });
  state = await rpc('get');
  check(state.selectedListId === firstId && state.data.lists.length === 2, 'list data and current selection survive actual worker restart');
  state = await rpc('sync');
  check(state.sync.connected && !state.sync.pending, 'folder handle and fingerprint survive actual worker restart');
  const externallyEdited = JSON.parse(await readDirectoryFile('valid-lists'));
  externallyEdited.lists.find(x => x.id === secondId).name = 'Правка извне';
  const externallyEditedText = JSON.stringify(externallyEdited, null, 2);
  await prepareDirectory('valid-lists', externallyEditedText);
  state = await rpc('addItem', { listId: firstId, url: 'https://example.com/conflict', title: 'Конфликт', comment: '', tags: [] });
  check(state.sync.pending && Boolean(state.sync.error), 'external JSON edit marks sync conflict');
  check(await readDirectoryFile('valid-lists') === externallyEditedText, 'external JSON edits are never silently overwritten');
  state = await rpc('connectDirectory');
  check(state.data.lists.some(x => x.name === 'Правка извне') && !state.sync.pending, 'explicit reconnect safely merges external file');
  const worker = browser.serviceWorkers().find(target => target.url() === `chrome-extension://${id}/background.js`);
  assert.ok(worker, 'restarted worker is reachable');
  const beforePermissionLoss = await readDirectoryFile('valid-lists');
  await worker.evaluate(() => { globalThis.__queryPermissionOriginal = FileSystemDirectoryHandle.prototype.queryPermission; FileSystemDirectoryHandle.prototype.queryPermission = async () => 'denied'; });
  state = await rpc('addItem', { listId: firstId, url: 'https://example.com/permission', title: 'Без доступа', comment: '', tags: [] });
  check(state.sync.pending && state.data.lists.find(x => x.id === firstId).items.some(x => x.title === 'Без доступа'), 'revoked folder permission preserves local save and marks pending');
  check(await readDirectoryFile('valid-lists') === beforePermissionLoss, 'permission denial leaves disk copy unchanged');
  await worker.evaluate(() => { FileSystemDirectoryHandle.prototype.queryPermission = globalThis.__queryPermissionOriginal; delete globalThis.__queryPermissionOriginal; });
  state = await rpc('sync');
  check(!state.sync.pending, 'sync resumes after folder permission returns');
  state = await rpc('removeItem', { listId: firstId, itemId });
  disk = JSON.parse(await readDirectoryFile('valid-lists'));
  check(!disk.lists.find(x => x.id === firstId).items.some(x => x.id === itemId), 'removing URL persists to JSON without resurrection');
  await rpc('disconnectDirectory');
  const invalidText = '{this is not valid JSON';
  await prepareDirectory('invalid-lists', invalidText);
  const invalidConnect = await raw('connectDirectory');
  check(!invalidConnect.ok || invalidConnect.state.sync.pending || !invalidConnect.state.sync.connected, 'invalid existing folder file blocks connection');
  await rpc('addItem', { listId: firstId, url: 'https://example.net/local-only', title: 'Локально', comment: '', tags: [] });
  await raw('sync');
  check(await readDirectoryFile('invalid-lists') === invalidText, 'failed connect followed by save never overwrites invalid file');
  state = await rpc('get');
  check(state.data.lists.find(x => x.id === firstId).items.some(x => x.url.includes('local-only')), 'file failure preserves new local record');
  await rpc('disconnectDirectory');
  const mergedImport = JSON.parse(JSON.stringify(state.data));
  mergedImport.lists[0].name = 'Коллизия ID';
  state = await rpc('importData', { data: mergedImport });
  check(state.data.lists.some(x => x.name === 'SEO сайты') && state.data.lists.some(x => x.name === 'Коллизия ID'), 'colliding import IDs preserve both distinct lists');
  await rpc('selectList', { listId: firstId });
  await page.reload();
  await page.waitForFunction(() => document.querySelector('#rows').textContent.includes('Локально'));
  check((await page.locator('body').textContent()).includes('Локально'), 'library table renders selected list records');
  check(await page.locator('table img, table script').count() === 0, 'URL titles and comments cannot inject markup into library');
  fs.mkdirSync(path.join(__dirname, 'artifacts'), { recursive: true });
  await page.screenshot({ path: path.join(__dirname, 'artifacts', 'library.png'), fullPage: true });
  const popup = await browser.newPage();
  await popup.goto(`chrome-extension://${id}/popup.html`);
  await popup.locator('[data-tab="lists"]').click();
  check(await popup.locator('#lists').isVisible(), 'quick save panel opens independently of SEO analysis failure');
  await popup.waitForFunction(expected => document.querySelector('#list-select').value === expected, firstId);
  await popup.evaluate(() => { chrome.tabs.query = async () => [{ id: 123, url: 'https://current-page.example/test', title: 'Текущая страница' }]; });
  await popup.locator('#list-comment').fill('Из popup');
  await popup.locator('#list-tag-suggestions button').filter({ hasText: /^follow$/ }).click();
  await popup.locator('#save-list-page').click();
  await popup.waitForFunction(() => document.querySelector('#list-status').textContent.includes('Страница сохранена'));
  state = await rpc('get');
  check(state.data.lists.find(x => x.id === firstId).items.some(x => x.url === 'https://current-page.example/test' && x.comment === 'Из popup' && x.tags.includes('follow')), 'popup saves current URL with comment and selected existing tag to active list');
  await page.locator('#filter').fill('Из popup');
  await page.waitForFunction(() => document.querySelectorAll('#rows tr').length === 1);
  await page.locator('#rows textarea').fill('Изменено в таблице');
  await page.locator('#rows input').fill('edited, follow');
  await page.locator('#rows .primary').click();
  await page.waitForFunction(() => document.querySelector('#message').textContent.includes('Изменения сохранены'));
  state = await rpc('get');
  check(state.data.lists.find(x => x.id === firstId).items.some(x => x.comment === 'Изменено в таблице' && x.tags.includes('edited')), 'library table edits comments and free tags');
  await page.locator('#filter').fill('edited');
  await page.waitForFunction(() => document.querySelectorAll('#rows tr').length === 1);
  check((await page.locator('#rows').textContent()).includes('current-page.example'), 'table filter searches saved tags');
  const downloadEvent = page.waitForEvent('download');
  await page.locator('#export-data').click();
  const download = await downloadEvent;
  const downloaded = JSON.parse(fs.readFileSync(await download.path(), 'utf8'));
  check(download.suggestedFilename() === 'seo-lists.json' && downloaded.lists.some(x => x.items.some(y => y.tags.includes('edited'))), 'JSON export contains current comments and tags');
  await page.locator('#filter').fill('');
  await page.screenshot({ path: path.join(__dirname, 'artifacts', 'library.png'), fullPage: true });
  await popup.locator('[data-tab="links"]').click();
  const input = await popup.locator('#links-domain').boundingBox();
  const button = await popup.locator('#highlight-links').boundingBox();
  const clear = await popup.locator('#links .clear').boundingBox();
  check(input && button && clear && Math.abs(input.y - button.y) < 5 && Math.abs(input.y - clear.y) < 5, 'LINKS filter and buttons occupy one horizontal row');
  check(await popup.locator('#links p.hint').count() === 0, 'LINKS explanatory paragraph removed');
  check(errors.length === 0, 'library has no uncaught JavaScript exceptions');
  console.log(`PASS ${checks} saved-list integration checks`);
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => { await browser?.close(); });

/* History chip behavior against actual extension Chrome storage. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
let browser;
let checks = 0;
const check = (condition, label) => { assert.ok(condition, label); checks++; console.log(`PASS ${label}`); };
(async () => {
  const chromePath = 'C:/Program Files/Google/Chrome/Application/chrome.exe';
  browser = await chromium.launchPersistentContext('', { executablePath: process.env.CHROME_PATH || (fs.existsSync(chromePath) ? chromePath : undefined), headless: true, viewport: { width: 800, height: 660 }, args: ['--enable-unsafe-extension-debugging'], ignoreDefaultArgs: ['--disable-extensions'] });
  const cdp = await browser.browser().newBrowserCDPSession();
  const { id } = await cdp.send('Extensions.loadUnpacked', { path: path.resolve(__dirname, '..') });
  const page = await browser.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`chrome-extension://${id}/library.html`);
  await page.evaluate(() => chrome.storage.local.set({ searchTargetDomain: 'remembered.example', searchQuery: 'Старый запрос', linksDomain: 'links.example' }));
  await page.goto(`chrome-extension://${id}/popup.html`);
  await page.locator('[data-tab="search"]').click();
  const values = container => page.locator(`#${container} .history-value`);
  const storage = key => page.evaluate(async key => (await chrome.storage.local.get(key))[key], key);
  const commit = async (field, value) => { await page.locator(`#${field}`).fill(value); await page.locator(`#${field}`).press('Tab'); };
  await page.waitForFunction(() => document.querySelector('#history-search-domain').textContent.includes('remembered.example'));
  check((await storage('historySearchDomains')).includes('remembered.example'), 'remembered search domain migrates into initially missing history');
  check((await storage('historySearchQueries')).includes('Старый запрос'), 'remembered query migrates into its own history');
  check((await storage('historyLinksDomains')).includes('links.example'), 'remembered LINKS filter migrates independently');
  await page.locator('#search-domain').fill('typed-but-not-committed.example');
  check(!(await storage('historySearchDomains')).includes('typed-but-not-committed.example'), 'typing does not create partial history entries');
  await page.locator('#search-domain').press('Tab');
  await page.waitForFunction(async () => (await chrome.storage.local.get('historySearchDomains')).historySearchDomains.includes('typed-but-not-committed.example'));
  check(true, 'committing field records full domain');
  await commit('search-domain', '  Example.COM  ');
  await page.waitForFunction(async () => (await chrome.storage.local.get('historySearchDomains')).historySearchDomains.some(x => x.toLowerCase() === 'example.com'));
  await commit('search-domain', 'example.com');
  await page.waitForFunction(async () => (await chrome.storage.local.get('historySearchDomains')).historySearchDomains[0] === 'example.com');
  let history = await storage('historySearchDomains');
  check(history.filter(x => x.toLowerCase() === 'example.com').length === 1 && history[0] === 'example.com', 'domain history trims, deduplicates without case and puts recent first');
  await commit('search-domain', '   ');
  check((await storage('historySearchDomains')).every(x => x.trim().length > 0), 'empty values are never recorded');
  const tabsBefore = (await browser.pages()).length;
  await page.locator('#history-search-domain').getByRole('button', { name: 'remembered.example', exact: true }).click();
  check(await page.locator('#search-domain').inputValue() === 'remembered.example', 'history chip applies domain to input');
  await page.waitForFunction(async () => (await chrome.storage.local.get('searchTargetDomain')).searchTargetDomain === 'remembered.example');
  check((await browser.pages()).length === tabsBefore, 'history selection never launches search');
  await commit('search-query', 'ремонт квартиры');
  await page.waitForFunction(async () => (await chrome.storage.local.get('historySearchQueries')).historySearchQueries.includes('ремонт квартиры'));
  check(!(await storage('historySearchDomains')).includes('ремонт квартиры'), 'query and domain histories remain separate');
  const active = await page.locator('#search-domain').inputValue();
  const chip = page.locator('#history-search-domain .history-chip').filter({ has: page.getByRole('button', { name: 'example.com', exact: true }) });
  await chip.locator('.history-remove').click();
  await page.waitForFunction(async () => !(await chrome.storage.local.get('historySearchDomains')).historySearchDomains.includes('example.com'));
  check(await page.locator('#search-domain').inputValue() === active, 'cross removes history only without selecting or clearing input');
  const currentChip = page.locator('#history-search-domain .history-chip').filter({ has: page.getByRole('button', { name: 'remembered.example', exact: true }) });
  await currentChip.locator('.history-remove').click();
  await page.waitForFunction(async () => !(await chrome.storage.local.get('historySearchDomains')).historySearchDomains.includes('remembered.example'));
  await page.reload();
  await page.locator('[data-tab="search"]').click();
  check(!(await storage('historySearchDomains')).includes('remembered.example') && await page.locator('#search-domain').inputValue() === 'remembered.example', 'deleted active chip stays deleted after reopen while current domain remains');
  for (let n = 0; n < 14; n++) await commit('search-domain', `domain-${n}.example`);
  await page.waitForFunction(async () => (await chrome.storage.local.get('historySearchDomains')).historySearchDomains[0] === 'domain-13.example');
  history = await storage('historySearchDomains');
  check(history.length === 12 && history[0] === 'domain-13.example' && !history.includes('domain-0.example'), 'history retains only twelve recent values');
  await page.locator('#search-query').fill('Запрос Enter');
  await page.locator('#search-query').press('Enter');
  await page.waitForFunction(async () => (await chrome.storage.local.get('historySearchQueries')).historySearchQueries.includes('Запрос Enter'));
  check(true, 'Enter commits history without a search launch');
  await page.locator('[data-tab="links"]').click();
  await commit('links-domain', 'external.example');
  await page.waitForFunction(async () => (await chrome.storage.local.get('historyLinksDomains')).historyLinksDomains.includes('external.example'));
  check(!(await storage('historySearchDomains')).includes('external.example'), 'LINKS history is independent of SEARCH');
  await page.locator('#history-links-domain').getByRole('button', { name: 'links.example', exact: true }).click();
  await page.waitForFunction(async () => (await chrome.storage.local.get('linksDomain')).linksDomain === 'links.example');
  check(await page.locator('#links-domain').inputValue() === 'links.example', 'LINKS chip applies and persists filter through existing handler');
  const malicious = '<img src=x onerror=alert(1)>';
  await page.evaluate(value => chrome.storage.local.set({ historySearchDomains: [value], historySearchQueries: [null, 5, {}, 'safe query'], historyLinksDomains: 'malformed' }), malicious);
  await page.reload();
  await page.locator('[data-tab="search"]').click();
  await page.waitForFunction(() => document.querySelector('#history-search-domain').textContent.includes('<img'));
  check(await page.locator('#history-search-domain img').count() === 0, 'history values are rendered as text without markup injection');
  check((await values('history-search-query').allTextContents()).includes('safe query'), 'malformed history entries cannot break valid entries');
  await page.locator('[data-tab="links"]').click();
  check(await values('history-links-domain').count() <= 1, 'malformed stored history type safely normalizes');
  await page.locator('[data-tab="search"]').click();
  fs.mkdirSync(path.join(__dirname, 'artifacts'), { recursive: true });
  await page.screenshot({ path: path.join(__dirname, 'artifacts', 'history-search.png') });
  check(errors.length === 0, 'history UI has no uncaught exceptions');
  console.log(`PASS ${checks} history integration checks`);
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => { await browser?.close(); });
